#include <stdio.h>
#include <stdlib.h>
#include <math.h>

// Прототипи функцій
double math_function(double x);
double derivative_function(double x);


// ============================================================
// Функція main()
//
// МАТЕМАТИЧНИЙ РІВЕНЬ:
// Необхідно дослідити функцію f(x) та її першу похідну
// на заданому проміжку від X1 до X2.
//
// АЛГОРИТМІЧНИЙ РІВЕНЬ:
// 1. Вибір способу введення початкових даних.
// 2. Введення X1, X2 та N або delta.
// 3. Перевірка правильності введених даних.
// 4. Розрахунок кількості точок та кроку.
// 5. Обчислення значень функції та її похідної.
// 6. Виведення двох таблиць на екран.
//
// ПРОГРАМНИЙ РІВЕНЬ:
// Використовуються локальні змінні, оператори if, do...while,
// while, for, scanf() та printf().
// ============================================================

int main()
{
    double X1, X2, delta, x;
    int variant;
    int N, i, rows;

    // Вибір варіанту введення початкових даних
    do
    {
        printf("Choose input variant:\n");
        printf("1 - Enter number of points (N)\n");
        printf("2 - Enter step (delta)\n");
        printf("Your choice: ");

        scanf("%d", &variant);

    } while (variant != 1 && variant != 2);


    // Введення початкового та кінцевого значень аргументу
    do
    {
        printf("\nEnter X1: ");
        scanf("%lf", &X1);

        printf("Enter X2: ");
        scanf("%lf", &X2);

        if (X1 >= X2)
        {
            printf("Error! X1 must be less than X2.\n");
        }

    } while (X1 >= X2);


    // Перший варіант введення: кількість точок
    if (variant == 1)
    {
        do
        {
            printf("Enter number of points N (N >= 2): ");
            scanf("%d", &N);

        } while (N < 2);

        // Розрахунок кроку зміни аргументу
        delta = (X2 - X1) / (N - 1);

        rows = N;
    }

    // Другий варіант введення: крок зміни аргументу
    else
    {
        do
        {
            printf("Enter delta: ");
            scanf("%lf", &delta);

        } while (delta <= 0);

        // Визначення кількості точок
        rows = 0;
        x = X1;

        while (x <= X2)
        {
            rows++;
            x = x + delta;
        }
    }


    // Виведення введених початкових даних
    printf("\nInitial data:\n");
    printf("X1 = %.4lf\n", X1);
    printf("X2 = %.4lf\n", X2);
    printf("Delta = %.4lf\n", delta);
    printf("Number of points = %d\n", rows);


    // Таблиця значень математичної функції
    printf("\n-----------------------------------------------\n");
    printf("        TABLE OF FUNCTION f(x)\n");
    printf("-----------------------------------------------\n");

    printf("|  Point  |       X       |       f(x)        |\n");
    printf("-----------------------------------------------\n");

    for (i = 0; i < rows; i++)
    {
        x = X1 + i * delta;

        printf("| %7d | %13.4lf | %17.6lf |\n",
               i + 1, x, math_function(x));
    }

    printf("-----------------------------------------------\n");


    // Таблиця значень першої похідної функції
    printf("\n-----------------------------------------------\n");
    printf("       TABLE OF DERIVATIVE f'(x)\n");
    printf("-----------------------------------------------\n");

    printf("|  Point  |       X       |       f'(x)       |\n");
    printf("-----------------------------------------------\n");

    for (i = 0; i < rows; i++)
    {
        x = X1 + i * delta;

        printf("| %7d | %13.4lf | %17.6lf |\n",
               i + 1, x, derivative_function(x));
    }

    printf("-----------------------------------------------\n");

    return 0;
}


// ============================================================
// Функція math_function()
//
// МАТЕМАТИЧНИЙ РІВЕНЬ:
// Обчислення значення функції:
// f(x) = 4 * (x/10 - 2)^3 - 15*x + 12
//
// АЛГОРИТМІЧНИЙ РІВЕНЬ:
// Отримати значення аргументу x, підставити його
// у формулу функції та повернути результат обчислення.
//
// ПРОГРАМНИЙ РІВЕНЬ:
// Функція типу double отримує параметр x типу double.
// Оператор return повертає обчислене значення.
// Функція pow() підносить вираз до третього степеня.
// ============================================================

double math_function(double x)
{
    return 4 * pow(x / 10.0 - 2, 3) - 15 * x + 12;
}


// ============================================================
// Функція derivative_function()
//
// МАТЕМАТИЧНИЙ РІВЕНЬ:
// Обчислення першої похідної функції:
// f'(x) = 1.2 * (x/10 - 2)^2 - 15
//
// АЛГОРИТМІЧНИЙ РІВЕНЬ:
// Отримати значення аргументу x, підставити його
// у формулу першої похідної та повернути результат.
//
// ПРОГРАМНИЙ РІВЕНЬ:
// Функція типу double отримує параметр x типу double.
// Оператор return повертає результат обчислення.
// Функція pow() використовується для піднесення
// виразу до другого степеня.
// ============================================================

double derivative_function(double x)
{
    return 1.2 * pow(x / 10.0 - 2, 2) - 15;
}
